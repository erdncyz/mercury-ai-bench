export function inferOpenWeights(name: string, creator: string): boolean {
  if (OPEN_NAME.some((pattern) => pattern.test(name))) return true
  return OPEN_CREATORS.has(creator.trim().toLowerCase())
}

export function resolveOpenWeights(
  raw: Record<string, unknown>,
  name: string,
  creator: string,
): boolean {
  const explicit = raw.is_open_weights ?? raw.open_weights
  if (typeof explicit === 'boolean') return explicit
  return inferOpenWeights(name, creator)
}
